CREATE TABLE public.confirmation_codes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code_hash character varying(255) NOT NULL,
    sent_at timestamp(6) without time zone NOT NULL,
    expires_at timestamp(6) without time zone NOT NULL,
    used boolean NOT NULL DEFAULT false,
    failed_attempts integer NOT NULL DEFAULT 0,
    code_purpose character varying(255) NOT NULL,
    user_id bigint NOT NULL,
    CONSTRAINT fk_confirmation_codes_user
    FOREIGN KEY (user_id) REFERENCES public.users (id) ON DELETE CASCADE
);

CREATE INDEX idx_confirmation_codes_user_purpose
    ON public.confirmation_codes (user_id, code_purpose);